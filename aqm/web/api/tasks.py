# ── Auto-resume after a server restart ────────────────────────────────
# ``recover_stale_tasks`` marks in-progress tasks as stalled on startup.  The
# console used to leave them there, so every deployment interrupted whatever
# was running.  These helpers resume them automatically, with a short backoff
# to let the server finish booting and to avoid a crash loop.

AUTO_RESUME_LIMIT = 3
AUTO_RESUME_WINDOW_SECONDS = 600


def cleanup_stale_chunks(project_root: Path) -> int:
    """Release leftover in-progress work blocks after a server restart.

    A restart kills the members that had claimed blocks, so any block still
    marked "in progress" is stale.  Clearing them at boot keeps the panel
    honest (at most one block can be in progress per task, and nothing is
    running yet).
    """
    from aqm.core.chunks import ChunkManager

    tasks_dir = get_tasks_dir(project_root)
    if not tasks_dir.is_dir():
        return 0
    cleaned = 0
    for task_dir in tasks_dir.iterdir():
        if not task_dir.is_dir() or not (task_dir / "chunks.json").exists():
            continue
        try:
            released = ChunkManager(task_dir).release_in_progress()
        except Exception as exc:  # pragma: no cover - defensive
            logger.warning("Failed to clean chunks for %s: %s", task_dir.name, exc)
            continue
        if released:
            cleaned += len(released)
            logger.info(
                "[Chunk] released %d stale in-progress block(s) for %s",
                len(released), task_dir.name,
            )
    return cleaned


def auto_resume_stalled(
    project_root: Path,
    task_ids: list[str],
    delay: float = 2.0,
) -> None:
    """Resume server-restart stalls in a background thread."""
    if not task_ids:
        return
    threading.Thread(
        target=_auto_resume_worker,
        args=(project_root, list(task_ids), delay),
        daemon=True,
    ).start()


def _prepare_auto_resume(
    project_root: Path, task_id: str,
) -> tuple[bool, int | None]:
    """Decide whether *task_id* should be auto-resumed.

    Returns ``(resume, from_stage)``.  A guard limits repeated auto-resumes so
    a task that keeps killing the server does not turn into a boot loop.
    """
    queue = SQLiteQueue(get_db_path(project_root))
    try:
        task = queue.get(task_id)
        if task is None or task.status != TaskStatus.stalled:
            return False, None
        reason = str(task.metadata.get("stall_reason") or "")
        if reason != "Server restarted while task was running":
            # A stall set by anything else is a deliberate state; leave it.
            return False, None

        now = datetime.now(timezone.utc)
        checkpoint = task.metadata.get("_checkpoint_stage")
        from_stage = None
        if (
            isinstance(checkpoint, int)
            and 1 <= checkpoint <= len(task.stages) + 1
        ):
            from_stage = checkpoint
        target = from_stage
        if target is None:
            target = len(task.stages) if task.stages else 1

        # Only count repeated attempts at the *same* stage: once the task makes
        # progress, the resume budget starts over.
        last_target = task.metadata.get("_auto_resume_last_stage")
        recent: list[datetime] = []
        if last_target == target:
            for raw in task.metadata.get("_auto_resume_at") or []:
                try:
                    stamp = datetime.fromisoformat(str(raw))
                except (TypeError, ValueError):
                    continue
                if (now - stamp).total_seconds() <= AUTO_RESUME_WINDOW_SECONDS:
                    recent.append(stamp)
        if len(recent) >= AUTO_RESUME_LIMIT:
            task.metadata["stall_reason"] = (
                f"自动恢复已尝试 {len(recent)} 次仍停在阶段 {target}，"
                "请手动检查后重启任务"
            )
            queue.update(task)
            logger.warning(
                "[AutoResume] %s skipped after %d attempts at stage %s",
                task_id, len(recent), target,
            )
            return False, None

        recent.append(now)
        task.metadata["_auto_resume_at"] = [s.isoformat() for s in recent]
        task.metadata["_auto_resume_last_stage"] = target
        queue.update(task)
        return True, from_stage
    finally:
        queue.close()


def _auto_resume_worker(
    project_root: Path, task_ids: list[str], delay: float,
) -> None:
    time.sleep(max(0.0, delay))
    for task_id in task_ids:
        try:
            resume, from_stage = _prepare_auto_resume(project_root, task_id)
        except Exception as exc:  # pragma: no cover - defensive
            logger.warning("[AutoResume] %s skipped: %s", task_id, exc)
            continue
        if not resume:
            continue
        with _restarting_lock:
            if task_id in _restarting_tasks:
                continue
            _restarting_tasks.add(task_id)
        logger.warning(
            "[AutoResume] resuming %s (from_stage=%s)", task_id, from_stage
        )
        broadcast_event(task_id, "pipeline_restarting", {
            "from_stage": from_stage,
            "auto": True,
        })
        try:
            _restart_task_worker(
                project_root, task_id, from_stage, keep_pause=True
            )
        except Exception as exc:  # pragma: no cover - defensive
            logger.warning("[AutoResume] %s failed: %s", task_id, exc)



