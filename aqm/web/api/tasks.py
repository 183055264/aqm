# Guard against two restart threads racing on the same task (double-clicking
# "重启" used to spawn one pipeline run per click, all writing the same
# context/stage files).
_restarting_tasks: set[str] = set()
_restarting_lock = threading.Lock()

# Live resident-session status per task, used by the member roster on the
# task page ("启动中" → "常驻中").  Kept in memory: resident sessions are
# process-local, and the page re-fetches this after a reload.
_resident_status: dict[str, dict[str, str]] = {}
_resident_lock = threading.Lock()


def _resident_status_handler(task_id: str, agents: dict[str, AgentDefinition]):
    """Return an on_resident_event callback that tracks and broadcasts status."""

    def handler(state: str, data: dict | None = None) -> None:
        payload = dict(data or {})
        with _resident_lock:
            roster = _resident_status.get(task_id)
            if state == "starting":
                roster = {
                    str(aid): "starting" for aid in payload.get("agents", [])
                }
                _resident_status[task_id] = roster
            elif roster is None:
                roster = {str(aid): "starting" for aid in agents}
                _resident_status[task_id] = roster
            if state == "ready":
                agent_id = payload.get("agent_id")
                if agent_id:
                    roster[str(agent_id)] = "ready"
            elif state in ("failed", "cancelled"):
                for aid, status in list(roster.items()):
                    if status != "ready":
                        roster[aid] = state
        broadcast_event(task_id, f"resident_{state}", payload)

    return handler


def _chunk_event_handler(task_id: str):
    """Broadcast work-block events (split/update/warning) to the task page."""

    def handler(event_type: str, data: dict) -> None:
        broadcast_event(task_id, event_type, data)

    return handler


def _append_durable_note(task: Task, note: str) -> bool:
    """Persist a human note as a durable prompt directive.

    Used by "restart with note" and "start chunk with note": the note survives
    restarts and is appended to every subsequent agent prompt.
    """
    note = (note or "").strip()
    if not note:
        return False
    notes = task.metadata.setdefault("interjections", [])
    if note in notes:
        return False
    notes.append(note)
    log = task.metadata.setdefault("interjection_log", [])
    log.append({
        "text": note,
        "agent_id": "",
        "stage_number": 0,
        "at": datetime.now(timezone.utc).isoformat(),
    })
    task.touch()
    return True


