def _gate_waiting_event(root: Path, task: Task) -> dict:
    """Build the ``gate_waiting`` / ``GET /gate`` payload.

    The payload spells out what the reviewer is being asked to approve:
    explicit ``gate.prompt`` criteria when configured, otherwise the items
    extracted from the member's own output, plus pending work blocks and the
    consequences of approving or rejecting.
    """
    metadata = task.metadata or {}
    agents: dict[str, AgentDefinition] = {}
    try:
        agents_path = get_agents_yaml_path(root, metadata.get("pipeline"))
        if agents_path.exists():
            agents = load_agents(agents_path)
    except Exception:  # pragma: no cover - defensive
        agents = {}
    review = build_gate_review(task, agents, root)
    return {"agent_id": task.current_agent_id, "gate": review}


def task_snapshot(project_root: Path, task_id: str) -> dict:
    """Current run state sent as the first SSE frame.

    A reloaded (or reconnected) page has missed ``stage_start`` / ``task_paused``;
    this frame lets it rebuild the live block, timer and pause controls instead
    of sitting at "等待代理输出 0s" until the next event happens to arrive.
    """
    found = find_task(project_root, task_id)
    if found is None:
        return {"status": "unknown"}
    task, root = found
    md = task.metadata or {}
    agent_id = task.current_agent_id or str(md.get("_checkpoint_agent_id") or "")
    agent_name, runtime = agent_id, ""
    if agent_id:
        try:
            agents_path = get_agents_yaml_path(root, md.get("pipeline"))
            if agents_path.exists():
                agent = load_agents(agents_path).get(agent_id)
                if agent is not None:
                    agent_name = agent.name or agent.id
                    runtime = agent.runtime or ""
        except Exception:  # pragma: no cover - defensive
            pass
    checkpoint = md.get("_checkpoint_stage")
    stage_number = (
        checkpoint if isinstance(checkpoint, int) else task.next_stage_number
    )
    # A checkpoint ahead of the recorded stages means that stage is still
    # running (stage_start has fired, stage_complete has not).
    stage_running = (
        isinstance(checkpoint, int) and checkpoint > len(task.stages)
    )
    return {
        "status": task.status.value,
        "agent_id": agent_id,
        "agent_name": agent_name,
        "runtime": runtime,
        "stage_number": stage_number,
        "stage_running": stage_running,
        "started_at": (
            md.get("_stage_started_at") or md.get("run_started_at") or ""
        ),
        "paused": bool(md.get("paused")),
        "chunks_done": int(md.get("chunks_done") or 0),
        "chunks_total": int(md.get("chunks_total") or 0),
        "stages": len(task.stages),
    }


def _launch_restart(task_root: Path, task_id: str, from_stage: int | None) -> None:
    """Spawn the restart worker; separated so tests can stub the worker."""
    thread = threading.Thread(
        target=_restart_task_worker,
        args=(task_root, task_id, from_stage),
        daemon=True,
    )
    thread.start()


def run_pipeline_bg(
    project_root: Path,
    task: Task,
    start_agent: str,
    input_text: str | None,
    cli_params=None,
    pipeline: str | None = None,
) -> None:
    """Run a pipeline in a background thread with SSE broadcasting."""
    try:
        try:
            agents_path = get_agents_yaml_path(project_root, pipeline)
            agents = (
                load_agents(agents_path, cli_params=cli_params)
                if agents_path.exists()
                else {}
            )
        except ValueError as exc:
            broadcast_event(task.id, "task_failed", {
                "error": f"Pipeline configuration error: {exc}",
            })
            _persist_task_failure(project_root, task.id, exc)
            return
        queue = SQLiteQueue(get_db_path(project_root))
        project_config = load_project_config(project_root)
        resident_handler = _resident_status_handler(task.id, agents)
        pipe = Pipeline(
            agents,
            queue,
            project_root,
            config=project_config,
            resident_agents=project_config.pipeline.get("resident_agents", True),
            on_resident_event=resident_handler,
        )

        def on_stage_start(t, agent_id, stage_number):
            ag = agents.get(agent_id)
            broadcast_event(t.id, "stage_start", {
                "agent_id": agent_id,
                "stage_number": stage_number,
                "agent_name": ag.name if ag else agent_id,
                "runtime": ag.runtime if ag else "",
            })

        def on_stage_complete(t, stage):
            # Detect session turns for richer SSE events
            if stage.task_name.startswith("session:"):
                parts = stage.task_name.split(":")
                session_id = parts[1] if len(parts) > 1 else ""
                round_str = parts[2] if len(parts) > 2 else ""
                round_num = int(round_str[1:]) if round_str.startswith("r") else 0
                has_vote = "VOTE: AGREE" in stage.output_text.upper()
                broadcast_event(t.id, "turn_complete", {
                    "session_id": session_id,
                    "agent_id": stage.agent_id,
                    "round": round_num,
                    "stage_number": stage.stage_number,
                    "message_preview": stage.output_text[:300],
                    "agreed": has_vote,
                })
            else:
                broadcast_event(t.id, "stage_complete", {
                    "agent_id": stage.agent_id,
                    "stage_number": stage.stage_number,
                    "output_preview": stage.output_text[:200],
                    "gate_result": stage.gate_result,
                })

        def on_output(line):
            broadcast_event(task.id, "stage_output", {"text": line})

        def on_thinking(line):
            broadcast_event(task.id, "stage_thinking", {"text": line})

        def on_tool(event_type, data):
            broadcast_event(task.id, f"tool_{event_type}", data)

        def on_human_input_request(t, agent_id, questions):
            broadcast_event(t.id, "human_input_request", {
                "agent_id": agent_id,
                "questions": questions,
            })

        def on_interjection(t, notes, agent_id):
            broadcast_event(t.id, "interjection_applied", {
                "agent_id": agent_id,
                "notes": notes,
                "at": datetime.now(timezone.utc).isoformat(),
            })

        def on_stage_interrupted(t, agent_id, stage_number, notes):
            ag = agents.get(agent_id)
            broadcast_event(t.id, "stage_interrupted", {
                "agent_id": agent_id,
                "agent_name": ag.name if ag else agent_id,
                "runtime": ag.runtime if ag else "",
                "stage_number": stage_number,
                "notes": notes,
                "at": datetime.now(timezone.utc).isoformat(),
            })

        chunk_handler = _chunk_event_handler(task.id)

        # Work blocks: split the requirements document *before* the first stage
        # starts, so the task stays "pending" while the planner is thinking and
        # the members receive a complete list on their very first turn.
        try:
            from aqm.core.chunks import ChunkManager, resolve_chunk_settings

            chunk_settings = resolve_chunk_settings(project_config.chunks)
            chunk_mgr = ChunkManager(get_tasks_dir(project_root) / task.id)
            if (
                chunk_settings.get("enabled", True)
                and chunk_settings.get("auto_split", True)
                and not chunk_mgr.load().chunks
                and task.metadata.get("_chunk_split") not in ("failed", "skipped")
            ):
                pipe.split_task_chunks(
                    task,
                    replace=False,
                    keep_done=False,
                    on_chunk_event=chunk_handler,
                )
                queue.update(task)
        except Exception:  # noqa: BLE001 - planning must never block the run
            logger.exception("Chunk pre-split failed for %s", task.id)
            task.metadata["_chunk_split"] = "failed"
            queue.update(task)
            broadcast_event(task.id, "chunk_split_failed", {
                "error": "自动拆分工作块失败，任务继续执行",
            })

        result = pipe.run_task(
            task, start_agent,
            input_text=input_text,
            on_stage_complete=on_stage_complete,
            on_stage_start=on_stage_start,
            on_output=on_output,
            on_thinking=on_thinking,
            on_human_input_request=on_human_input_request,
            on_tool=on_tool,
            on_resident_event=resident_handler,
            on_interjection=on_interjection,
            on_stage_interrupted=on_stage_interrupted,
            on_chunk_event=chunk_handler,
        )

        if result.status == TaskStatus.awaiting_human_input:
            broadcast_event(task.id, "human_input_waiting", {
                "agent_id": result.current_agent_id,
                "pending": result.metadata.get("_human_input_pending", {}),
            })
        elif result.status == TaskStatus.awaiting_gate:
            broadcast_event(
                task.id, "gate_waiting", _gate_waiting_event(project_root, result)
            )
        elif result.status == TaskStatus.completed:
            event_data = {
                "status": "completed",
                "total_stages": len(result.stages),
            }
            # Include session consensus info
            if "session_consensus" in result.metadata:
                event_data["session_consensus"] = result.metadata["session_consensus"]
                event_data["session_rounds"] = result.metadata.get("session_rounds")
            broadcast_event(task.id, "task_complete", event_data)
        elif result.status == TaskStatus.failed:
            broadcast_event(task.id, "task_failed", {
                "error": result.metadata.get("error", "Unknown error"),
                "agent_id": result.current_agent_id,
            })
        queue.close()
    except Exception as e:
        logger.error("Pipeline execution failed: %s", e)
        _persist_task_failure(project_root, task.id, e)
        broadcast_event(task.id, "task_failed", {"error": str(e)})


def _split_chunks_bg(
    project_root: Path,
    task_id: str,
    replace: bool = True,
    keep_done: bool = True,
) -> dict:
    """Regenerate a task's work blocks from its requirements document.

    Returns a small result dict so the HTTP endpoint can report what happened.
    """
    queue = None
    try:
        found = find_task(project_root, task_id)
        if found is None:
            broadcast_event(task_id, "chunk_split_failed", {
                "error": "Task not found",
            })
            return {"created": 0, "error": "Task not found"}
        task, root = found
        queue = SQLiteQueue(get_db_path(root))
        cfg = load_project_config(root)
        pipeline_name = (task.metadata or {}).get("pipeline")
        agents_path = get_agents_yaml_path(root, pipeline_name)
        agents = (
            load_agents(agents_path) if agents_path.exists() else {}
        )
        pipe = Pipeline(
            agents,
            queue,
            root,
            config=cfg,
            resident_agents=False,
        )
        created = pipe.split_task_chunks(
            task,
            replace=replace,
            keep_done=keep_done,
            on_chunk_event=_chunk_event_handler(task_id),
            force=True,
        )
        queue.update(task)
        if not created:
            message = "模型没有返回可用的工作块，请检查需求文档"
            broadcast_event(task_id, "chunk_split_failed", {"error": message})
            return {"created": 0, "error": message}
        return {
            "created": len(created),
            "progress": pipe._update_chunk_metadata(task, pipe._chunk_manager(task)),
        }
    except Exception as exc:  # noqa: BLE001 - report to the UI, never crash
        logger.exception("Chunk split failed for %s", task_id)
        broadcast_event(task_id, "chunk_split_failed", {"error": str(exc)})
        return {"created": 0, "error": str(exc)}
    finally:
        if queue is not None:
            queue.close()


def start_pipeline_run(
    project_root: Path,
    description: str,
    *,
    pipeline: str | None = None,
    params: dict | None = None,
    metadata: dict | None = None,
) -> Task:
    """Create a task from *description*, enqueue it, and start it in the background.

    Shared by ``POST /api/run`` and the meeting handoff endpoint so both paths
    produce identical task records and SSE events.
    """
    from aqm.core.agent import get_entry_point, resolve_start_agent
    from aqm.core.project import get_default_pipeline

    pipeline_name = pipeline or get_default_pipeline(project_root) or "default"
    agents_path = get_agents_yaml_path(project_root, pipeline_name)
    agents = (
        load_agents(agents_path, cli_params=params) if agents_path.exists() else {}
    )
    if not agents:
        raise ValueError("No agents defined in the pipeline")
    entry_point = get_entry_point(agents_path)
    start_agent = (
        resolve_start_agent(description, agents)
        if entry_point == "auto"
        else next(iter(agents))
    )
    if start_agent not in agents:
        raise ValueError(f"Entry agent '{start_agent}' not found")

    task = Task(
        description=description,
        current_agent_id=start_agent,
        metadata={
            "pipeline": pipeline_name,
            "_pipeline_params": params or {},
            "project_dir": str(project_root.resolve()),
            **(metadata or {}),
        },
    )
    queue = SQLiteQueue(get_db_path(project_root))
    try:
        queue.push(task, queue_name=start_agent)
    finally:
        queue.close()

    threading.Thread(
        target=run_pipeline_bg,
        args=(project_root, task, start_agent, None, params, pipeline_name),
        daemon=True,
    ).start()
    return task


def _persist_task_failure(project_root: Path, task_id: str, error: Exception) -> None:
    queue = SQLiteQueue(get_db_path(project_root))
    try:
        task = queue.get(task_id)
        if task and task.status not in (
            TaskStatus.completed,
            TaskStatus.failed,
            TaskStatus.cancelled,
        ):
            task.status = TaskStatus.failed
            task.metadata["error"] = str(error)
            task.touch()
            queue.update(task)
    except Exception:
        logger.exception("Could not persist task failure for %s", task_id)
    finally:
        queue.close()


